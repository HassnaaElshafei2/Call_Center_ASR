/** Icons: Remix Icon line set (Sia UI Guidelines), behind the names the app already uses.
 *  Each export takes the same props as before: size, className, style, color/stroke, and fill (a fill colour switches to the
 *  filled variant, e.g. rating stars). */
import type { CSSProperties } from 'react'

type P = { size?: number; className?: string; style?: CSSProperties; color?: string; stroke?: string; fill?: string;
  strokeWidth?: number; 'aria-label'?: string; onClick?: () => void; title?: string }

function make(line: string, filled?: string) {
  const Icon = ({ size = 18, className = '', style, color, stroke, fill, ...rest }: P) => {
    const useFill = filled && fill && fill !== 'none'
    return <i className={`ri ri-${useFill ? filled : line} ${className}`} aria-hidden={rest['aria-label'] ? undefined : true}
      aria-label={rest['aria-label']} onClick={rest.onClick} title={rest.title} style={{ fontSize: size, color: useFill ? fill : (color ?? stroke), ...style }} />
  }
  Icon.displayName = line
  return Icon
}

